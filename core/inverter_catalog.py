def get_all_catalog_inverters() -> List[Inverter]:
    """Returns all inverters in the catalog as Inverter dataclasses."""
    inverters = []
    for d in INVERTER_CATALOG_DATA:
        inverters.append(Inverter(
            id=d["id"],
            manufacturer=d["manufacturer"],
            model=d["model"],
            rated_ac_power_kw=float(d["rated_ac_power_kw"]),
            max_dc_input_power_kw=float(d["max_dc_input_power_kw"]),
            max_dc_voltage_v=float(d["max_dc_voltage_v"]),
            mppt_voltage_min_v=float(d["mppt_voltage_min_v"]),
            mppt_voltage_max_v=float(d["mppt_voltage_max_v"]),
            mppt_count=int(d["mppt_count"]),
            string_inputs_per_mppt=int(d["string_inputs_per_mppt"]),
            max_input_current_per_mppt_a=float(d["max_input_current_per_mppt_a"]),
            max_isc_per_mppt_a=float(d["max_isc_per_mppt_a"]),
            max_total_dc_current_a=float(d["max_total_dc_current_a"]),
            ac_voltage=float(d["ac_voltage"]),
            rated_ac_current_a=float(d["rated_ac_current_a"]),
            max_ac_current_a=float(d["max_ac_current_a"]),
            efficiency_pct=float(d["efficiency_pct"]),
            recommended_dc_ac_ratio=float(d.get("recommended_dc_ac_ratio", 1.30)),
            grid_type=d.get("grid_type", "3-phase"),
            source="catalog",
            datasheet_file=d.get("datasheet", "")
        ))
    return inverters


def get_available_inverters(phase: Optional[int] = None, only_available: bool = True) -> List[Inverter]:
    """
    Returns inverters filtered by phase (1 or 3) and availability status.
    If phase is None, returns all inverters.
    """
    all_inv = get_all_catalog_inverters()
    filtered = []
    for inv, raw in zip(all_inv, INVERTER_CATALOG_DATA):
        if only_available and not raw.get("is_available", True):
            continue
        if phase is not None:
            target_grid = "1-phase" if phase == 1 else "3-phase"
            if inv.grid_type != target_grid:
                continue
        filtered.append(inv)
    return filtered



def get_inverter_by_model(model_name: str) -> Optional[Inverter]:
    """Finds an inverter by exact or partial model name."""
    for inv in get_all_catalog_inverters():
        if model_name.lower() in inv.model.lower() or inv.model.lower() in model_name.lower():
            return inv
    return None


def get_inverter_families() -> Dict[str, List[Dict]]:
    """
    Returns inverters grouped by manufacturer and series family.
    Useful for comparison tables and family-based UI displays.
    Returns dict: { "Sunways": [...], "KACO": [...] }
    """
    families: Dict[str, List[Dict]] = {}
    for d in INVERTER_CATALOG_DATA:
        mfr = d["manufacturer"]
        if mfr not in families:
            families[mfr] = []
        families[mfr].append({
            "model": d["model"],
            "rated_kw": d["rated_ac_power_kw"],
            "phases": 1 if d.get("grid_type") == "1-phase" else 3,
            "ac_voltage": d["ac_voltage"],
            "max_dc_v": d["max_dc_voltage_v"],
            "mppt_count": d["mppt_count"],
            "strings_per_mppt": d["string_inputs_per_mppt"],
            "mppt_range_v": f"{d['mppt_voltage_min_v']:.0f}–{d['mppt_voltage_max_v']:.0f}",
            "max_isc_a": d["max_isc_per_mppt_a"],
            "efficiency_pct": d["efficiency_pct"],
            "grid_type": d.get("grid_type", "3-phase"),
            "available": d.get("is_available", True),
            "datasheet": d.get("datasheet", ""),
        })
    # Sort each family by rated power ascending
    for mfr in families:
        families[mfr].sort(key=lambda x: x["rated_kw"])
    return families


def get_catalog_summary() -> Dict:
    """
    Returns a high-level summary of the inverter catalog.
    Used by the dashboard and equipment catalog pages.
    """
    all_inv = INVERTER_CATALOG_DATA
    manufacturers = list({d["manufacturer"] for d in all_inv})
    available = [d for d in all_inv if d.get("is_available", True)]
    max_kw = max((d["rated_ac_power_kw"] for d in available), default=0)
    min_kw = min((d["rated_ac_power_kw"] for d in available), default=0)
    phase1 = [d for d in available if d.get("grid_type") == "1-phase"]
    phase3 = [d for d in available if d.get("grid_type") == "3-phase"]
    return {
        "total_models": len(all_inv),
        "available_models": len(available),
        "manufacturers": sorted(manufacturers),
        "manufacturer_count": len(manufacturers),
        "min_rated_kw": min_kw,
        "max_rated_kw": max_kw,
        "single_phase_count": len(phase1),
        "three_phase_count": len(phase3),
        "max_system_capacity_kw": max_kw * 10,  # theoretical with 10 units
    }
